// Exports to <lang>/textbook what the book takes from the code decks of a language, so that the book
// prints the same files that the decks show and the tests check.
//   node textbook/export_listings.js <en|it>
//
//   code/lNN/cKK.<ext>   the listing of slide KK of the code deck of lecture NN
//   code/lNN/program.S   the complete program of the lecture (../../code/lNN.S)
//   code/lNN/lab.tex     the section "The program of this chapter", \input by the chapter
//   figures/lab_lNN.png  the frame that the test of the program wrote
//
// Listings are not translated: the export of "it" is byte-identical to that of "en" except where a
// listing is plain text (compare with  diff -r en/textbook/code it/textbook/code); lab.tex is text.
const fs = require("fs"), path = require("path");
const { LANGS, loadDecks, visible } = require("../lib/lang");
const lang = process.argv[2];
if (!LANGS.includes(lang)) { console.error("usage: node textbook/export_listings.js <" + LANGS.join("|") + ">"); process.exit(2); }
const BOOK = path.resolve(__dirname, "..", "..", lang, "textbook"), ASSETS = path.resolve(__dirname, "..", "assets");
const EXT = { asm: "S", sh: "sh", c: "c", txt: "txt", json: "json", py: "py", verilog: "v" };
const clean = (code) => String(code).replace(/\t/g, "    ").replace(/\s+$/, "") + "\n";
const tex = (s) => s.replace(/\\/g, "\\textbackslash{}").replace(/([_#%&])/g, "\\$1").replace(/~/g, "\\textasciitilde{}");

const T = {
  en: (l, c) => `% Generated by tools/textbook/export_listings.js from decks/plan.js and code/${l.src}.S: do not edit.
\\section{The program of this chapter}\\label{sec:lab:${l.src}}

The listings of this chapter are parts of one program, \\fname{code/${l.src}.S} in the
repository of the course, printed in full in Listing~\\ref{lst:lab:${l.src}}. The
automatic tests of the course material build it and run it on the headless
runner of \\prgqt{}, with scripted input, and check the frame;
Figure~\\ref{fig:lab:${l.src}} is the frame that the test wrote.

\\begin{description}[style=nextline,leftmargin=1.5em]
\\item[On the screen.] ${tex(cap(l.seeText))}
\\item[What to press.] ${tex(cap(l.keysText))}.
\\end{description}

\\begin{figure}[htb]
\\centering
\\includegraphics[width=0.5\\textwidth]{lab_${l.src}.png}
\\caption{\\fname{${l.src}.S} on \\prgqt{}.}\\label{fig:lab:${l.src}}
\\end{figure}

\\asmfile[caption={The complete program of the chapter, \\fname{code/${l.src}.S}.},label=lst:lab:${l.src}]{code/l${l.n}/program.S}

To run it on \\prgqt{} the commands are those of Listing~\\ref{lst:lab:${l.src}:run};
Section~\\ref{sec:prg:testing} gives the same steps for QEMU and for the board.

\\begin{shell}[caption={Building \\fname{${l.src}.S} and running it on \\prgqt{}.},label=lst:lab:${l.src}:run]
${c}
\\end{shell}
`,
  it: (l, c) => `% Generated by tools/textbook/export_listings.js from decks/plan.js and code/${l.src}.S: do not edit.
\\section{Il programma di questo capitolo}\\label{sec:lab:${l.src}}

I listati di questo capitolo sono parti di un solo programma,
\\fname{code/${l.src}.S} nel repository del corso, stampato per intero nel
Listato~\\ref{lst:lab:${l.src}}. I test automatici del materiale del corso lo
compilano e lo eseguono sull'esecutore senza interfaccia di \\prgqt{}, con
ingressi programmati, e controllano il frame; la
Figura~\\ref{fig:lab:${l.src}} è il frame scritto dal test.

\\begin{description}[style=nextline,leftmargin=1.5em]
\\item[Sullo schermo.] ${tex(cap(l.seeText))}
\\item[Che cosa premere.] ${tex(cap(l.keysText))}.
\\end{description}

\\begin{figure}[htb]
\\centering
\\includegraphics[width=0.5\\textwidth]{lab_${l.src}.png}
\\caption{\\fname{${l.src}.S} su \\prgqt{}.}\\label{fig:lab:${l.src}}
\\end{figure}

\\asmfile[caption={Il programma completo del capitolo, \\fname{code/${l.src}.S}.},label=lst:lab:${l.src}]{code/l${l.n}/program.S}

Per eseguirlo su \\prgqt{} i comandi sono quelli del
Listato~\\ref{lst:lab:${l.src}:run}; il Paragrafo~\\ref{sec:prg:testing} dà gli
stessi passi per QEMU e per la scheda.

\\begin{shell}[caption={Compilare \\fname{${l.src}.S} ed eseguirlo su \\prgqt{}.},label=lst:lab:${l.src}:run]
${c}
\\end{shell}
`,
};
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const map = {};          // "NN/sKK.ext" (the old name, by slide of the specification) -> "NN/cKK.ext"
for (const d of loadDecks(lang).filter((x) => x.kind === "code")) {
  const dir = path.join(BOOK, "code", "l" + d.n), keep = new Set();
  fs.mkdirSync(dir, { recursive: true });
  visible(d).forEach((s, i) => {
    if (s.gen) return;
    const code = s.t === "code" || s.t === "walk" ? s.a[1] : s.t === "bullets" && s.a[3] && s.a[3].code ? s.a[3].code : null;
    if (code == null) return;
    const l = s.t === "code" ? s.a[4] || "asm" : s.t === "walk" ? "asm" : s.a[3].lang || "asm", ext = EXT[l] || l;
    const f = `c${String(i + 2).padStart(2, "0")}.${ext}`;
    fs.writeFileSync(path.join(dir, f), clean(code)); keep.add(f);
    map[`l${d.n}/s${String(s.src[0]).padStart(2, "0")}.${ext}`] = `l${d.n}/${f}`;
  });
  const l = d.lab;
  if (l.src) {
    fs.copyFileSync(path.resolve(__dirname, "..", "..", "code", l.src + ".S"), path.join(dir, "program.S")); keep.add("program.S");
    const qt = visible(d).find((s) => s.gen === "qt").a[1];
    fs.writeFileSync(path.join(dir, "lab.tex"), T[lang](l, qt)); keep.add("lab.tex");
    fs.copyFileSync(path.join(ASSETS, l.shot), path.join(BOOK, "figures", l.shot));
  }
  // remove the listings of an earlier export (cKK, and the sKK of the single-deck layout); other files stay
  for (const f of fs.readdirSync(dir)) if (!keep.has(f) && /^[cs]\d\d\./.test(f)) fs.unlinkSync(path.join(dir, f));
}
if (process.env.LISTING_MAP) fs.writeFileSync(process.env.LISTING_MAP, JSON.stringify(map, null, 1));
console.log(`${lang}: ${Object.keys(map).length} listings exported to ${path.relative(process.cwd(), path.join(BOOK, "code"))}`);
