#!/usr/bin/env python3
"""Writes <lang>/textbook/frontmatter/picture_credits.tex: the credit of every picture of the book
that comes from Wikimedia Commons, from tools/assets/credits.json (see tools/assets/CREDITS.md).

    python3 textbook/gen_credits.py [en|it]
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
L = {"en": ("Picture credits.", "The photographs and the diagrams listed here come from Wikimedia Commons and keep "
            "their own licences; the other figures were made for this book. In the order of the file names: "),
     "it": ("Crediti delle immagini.", "Le fotografie e gli schemi elencati qui provengono da Wikimedia Commons e "
            "conservano le proprie licenze; le altre figure sono state realizzate per questo libro. "
            "Nell'ordine dei nomi dei file: ")}
def tex(s):
    s = s.replace("\\", "/")
    s = re.sub(r"([_#%&$])", r"\\\1", s)
    return s.replace("²", "$^2$").replace("°", "\\textdegree{}")
for lang in ([sys.argv[1]] if len(sys.argv) > 1 else ["en", "it"]):
    book = os.path.join(ROOT, lang, "textbook")
    src = "".join(open(os.path.join(book, d, f), encoding="utf8").read() for d in ("chapters", "appendices", "frontmatter")
                  for f in sorted(os.listdir(os.path.join(book, d))) if f.endswith(".tex") and f != "picture_credits.tex")
    used = [c for c in json.load(open(os.path.join(ROOT, "tools", "assets", "credits.json"), encoding="utf8")) if "{" + c["file"] + "}" in src]
    head, intro = L[lang]
    items = "; ".join(f"\\fname{{{tex(c['file'])}}}: \\emph{{{tex(re.sub(r'\.(jpe?g|png|svg|JPG)$', '', c['title']))}}}, {tex(c['author'])}, {tex(c['licence'])}" for c in used)
    out = (f"% Generated by tools/textbook/gen_credits.py from tools/assets/credits.json: do not edit.\n"
           f"\\noindent{{\\footnotesize\\textbf{{{head}}} {intro}{items}.\\par}}\n")
    open(os.path.join(book, "frontmatter", "picture_credits.tex"), "w", encoding="utf8").write(out)
    print(f"{lang}: {len(used)} picture credits")
